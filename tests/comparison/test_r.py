"""Tests against R marginaleffects reference outputs.

Reference outputs are generated by ``generate_r.R``.
These tests are skipped if the reference files are not present.
"""

import pathlib
import numpy as np
import pandas as pd
import pytest
import statsmodels.formula.api as smf
import statsmodels.api as sm
from numpy.testing import assert_allclose

from smmargins import Margins

HERE = pathlib.Path(__file__).parent


def _read_r_csv(path: pathlib.Path):
    return pd.read_csv(path)


def _match_label(ame_labels, r_term):
    """Match an R term (e.g. 'x1') to a smmargins label (e.g. 'dx1').

    smmargins prefixes derivative labels with 'd' (dydx) or 'e' (eyex/eydx).
    We strip the first character when the label otherwise equals the term.
    """
    labels = np.array(ame_labels)
    for prefix in ("d", "e"):
        stripped = np.array([lab[len(prefix):] if lab.startswith(prefix) else lab for lab in labels])
        mask = stripped == r_term
        if np.any(mask):
            return np.where(mask)[0][0]
    return None


