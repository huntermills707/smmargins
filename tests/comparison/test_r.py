# ---------------------------------------------------------------------------
# 3. OLS bootstrap
# ---------------------------------------------------------------------------
@pytest.mark.skipif(
    not (HERE / "r_ols_bootstrap.csv").exists(),
    reason="R reference output not found",
)
def test_ols_bootstrap_matches_r(df_seed12345):
    fit = smf.ols("y_ols ~ x1 + x2", data=df_seed12345).fit()
    M = Margins(fit)
    ame = M.dydx(["x1", "x2"], vce="bootstrap", n_boot=1000, boot_seed=42)

    ref = _read_r_csv(HERE / "r_ols_bootstrap.csv")
    for i, row in ref.iterrows():
        idx = _match_label(ame.labels, row["term"])
        assert idx is not None, f"No label match for R term {row['term']} in {ame.labels}"
        assert_allclose(ame.estimate[idx], row["estimate"], atol=1e-10)
        # R inferences() returns percentile CIs but no SE; derive approximate SE
        if "std.error" in row and pd.notna(row["std.error"]):
            r_se = row["std.error"]
        else:
            # Normal approximation: SE = (CI_upper - CI_lower) / (2 * 1.96)
            r_se = (row["conf.high"] - row["conf.low"]) / (2 * 1.96)
        mc_tol = 5 * max(ame.se[idx], r_se) / np.sqrt(1000)
        assert abs(ame.se[idx] - r_se) < mc_tol


