# 6. Logit AME at specific x2 values (migrated from Stata reference)
# ---------------------------------------------------------------------------
@pytest.mark.skipif(
    not (HERE / "r_logit_at.csv").exists(),
    reason="R reference output not found",
)
def test_logit_at_matches_r(df_seed42):
    fit = smf.logit("y_logit ~ x1 + x2 + C(grp)", data=df_seed42).fit(disp=False)
    M = Margins(fit)
    ame = M.dydx("x1", atexog={"x2": [-1, 0, 1]})

    ref = _read_r_csv(HERE / "r_logit_at.csv")
    for i, row in ref.iterrows():
        # Match by x2 value embedded in the smmargins label.
        # Use a precise suffix match to avoid "1" matching "x2=-1".
        x2_val = row["x2"]
        suffix = f"x2={x2_val}"
        mask = np.array([lab.endswith(suffix) for lab in ame.labels])
        assert np.any(mask), f"No label match for x2={x2_val} in {ame.labels}"
        idx = np.where(mask)[0][0]
        assert_allclose(ame.estimate[idx], row["estimate"], atol=1e-5)
        assert_allclose(ame.se[idx], row["std.error"], atol=1e-4)


