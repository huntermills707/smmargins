# ---------------------------------------------------------------------------
# 1. Logit AME with HC3
# ---------------------------------------------------------------------------
@pytest.mark.skipif(
    not (HERE / "r_logit_ame_hc3.csv").exists(),
    reason="R reference output not found",
)
def test_logit_ame_hc3_matches_r(df_seed42):
    fit = smf.logit("y_logit ~ x1 + x2 + C(grp)", data=df_seed42).fit(disp=False)
    M = Margins(fit, cov_type="HC3")
    ame = M.dydx(["x1", "x2"])

    ref = _read_r_csv(HERE / "r_logit_ame_hc3.csv")
    for i, row in ref.iterrows():
        if row["term"] in ("grp",):
            # smmargins handles factor contrasts differently; skip
            continue
        idx = _match_label(ame.labels, row["term"])
        assert idx is not None, f"No label match for R term {row['term']} in {ame.labels}"
        assert_allclose(ame.estimate[idx], row["estimate"], atol=1e-6)
        assert_allclose(ame.se[idx], row["std.error"], atol=5e-5)


